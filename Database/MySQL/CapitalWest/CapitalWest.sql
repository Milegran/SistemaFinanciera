  CONSTRAINT ck_tasa_valor CHECK (Porcentaje >= 0),
  CONSTRAINT ck_tasa_tipo CHECK (TipoTasa IN ('NOMINAL_ANUAL','EFECTIVA_ANUAL')),
  CONSTRAINT ck_tasa_fechas CHECK (VigenteHasta IS NULL OR VigenteHasta >= VigenteDesde)
